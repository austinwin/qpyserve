"""Deployment asset generation and non-destructive behavior tests."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from qpyserve._cli import create_project, main
from qpyserve._ship import prepare_ship


@pytest.mark.parametrize("template", ["html", "react", "vue"])
def test_ship_generates_valid_reviewable_assets(tmp_path: Path, template: str) -> None:
    project = create_project(tmp_path / f"my-{template}", template=template)
    output = prepare_ship(project)
    assert output["deployed"] is False
    assert output["service"] == f"my-{template}"
    assert output["frontend"] == ("html" if template == "html" else "vite")
    assert set(output["files"]) == {
        "Dockerfile", ".dockerignore", "docker-start.py", "render.yaml",
    }
    startup = (project / "docker-start.py").read_text()
    compile(startup, str(project / "docker-start.py"), "exec")
    assert 'host="0.0.0.0"' in startup
    assert 'mode="production"' in startup
    assert 'os.environ.get("PORT", "10000")' in startup

    dockerfile = (project / "Dockerfile").read_text()
    assert dockerfile.startswith("# Generated by qpyserve ship.")
    assert 'CMD ["python", "docker-start.py"]' in dockerfile
    assert "qpyserve>=0.4,<1" in dockerfile
    assert "RUN python -m pip install" in dockerfile
    assert "fi\nEXPOSE 10000" in dockerfile
    assert "\\nEXPOSE" not in dockerfile
    assert (project / "render.yaml").read_text().startswith("services:\n")
    assert "healthCheckPath: /__qpyserve/health" in (project / "render.yaml").read_text()
    assert "plan: free" in (project / "render.yaml").read_text()
    assert ".env" in (project / ".dockerignore").read_text()
    assert "node_modules" in (project / ".dockerignore").read_text()
    if template == "html":
        assert "frontend-build" not in dockerfile
    else:
        assert "frontend-build" in dockerfile
        assert "COPY --from=frontend-build" in dockerfile


def test_ship_does_not_overwrite_existing_deployment_files(tmp_path: Path) -> None:
    project = create_project(tmp_path / "existing")
    (project / ".dockerignore").write_text("CUSTOM\n")
    with pytest.raises(FileExistsError, match="Would overwrite"):
        prepare_ship(project)
    assert (project / ".dockerignore").read_text() == "CUSTOM\n"
    assert not (project / "Dockerfile").exists()
    assert not (project / "docker-start.py").exists()


def test_ship_accepts_custom_app_and_service_name(tmp_path: Path) -> None:
    project = create_project(tmp_path / "custom")
    (project / "api.py").write_text("from fastapi import FastAPI\napi = FastAPI()\n")
    result = prepare_ship(project, app_import="api:api", service_name="water-map")
    assert result["service"] == "water-map"
    assert "api:api" in (project / "docker-start.py").read_text()
    assert "name: water-map" in (project / "render.yaml").read_text()


@pytest.mark.parametrize("app_import", [
    "main", "main:app;import os", "../main:app", "main:app/foo", "main:app\\n",
])
def test_ship_rejects_invalid_app_import(tmp_path: Path, app_import: str) -> None:
    project = create_project(tmp_path / "invalid")
    with pytest.raises(ValueError, match="App import"):
        prepare_ship(project, app_import=app_import)


def test_ship_rejects_missing_module_and_bad_service_name(tmp_path: Path) -> None:
    project = create_project(tmp_path / "missing")
    with pytest.raises(FileNotFoundError, match="module"):
        prepare_ship(project, app_import="unknown:app")
    with pytest.raises(ValueError, match="service name"):
        prepare_ship(project, service_name="UPPER_case")


@pytest.mark.parametrize(
    ("manager", "lockfile", "expected"),
    [
        ("npm", "package-lock.json", "npm ci"),
        ("pnpm", "pnpm-lock.yaml", "pnpm install --frozen-lockfile"),
        ("yarn", "yarn.lock", "yarn install"),
        ("bun", "bun.lock", "bun install --frozen-lockfile"),
    ],
)
def test_ship_supports_project_package_manager(
    tmp_path: Path, manager: str, lockfile: str, expected: str,
) -> None:
    project = create_project(tmp_path / manager, template="react")
    frontend = project / "frontend"
    config = json.loads((frontend / "package.json").read_text())
    config["packageManager"] = f"{manager}@1.0.0"
    (frontend / "package.json").write_text(json.dumps(config))
    (frontend / lockfile).touch()
    prepare_ship(project)
    dockerfile = (project / "Dockerfile").read_text()
    assert expected in dockerfile
    assert "FROM oven/bun:1" in dockerfile if manager == "bun" else "FROM node:22" in dockerfile


def test_ship_json_reports_dry_generation(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    project = create_project(tmp_path / "my-app")
    assert main(["ship", str(project), "--json"]) == 0
    result = json.loads(capsys.readouterr().out)
    assert result["deployed"] is False
    assert result["frontend"] == "html"
    assert len(result["files"]) == 4


def test_ship_rejects_frontend_symlink(tmp_path: Path) -> None:
    project = create_project(tmp_path / "linked")
    frontend = project / "frontend"
    backup = tmp_path / "actual"
    frontend.rename(backup)
    try:
        frontend.symlink_to(backup, target_is_directory=True)
    except (OSError, NotImplementedError):
        pytest.skip("Platform disallows symlinks")
    with pytest.raises(ValueError, match="Frontend must be inside"):
        prepare_ship(project)
