"""Typed browser API generation from FastAPI OpenAPI without extra dependencies."""

from __future__ import annotations

from dataclasses import dataclass
import importlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile
from typing import Any

from fastapi import FastAPI

_MARKER = "// Generated by QPyServe API. Do not edit this file by hand."
_METHODS = ("get", "post", "put", "patch", "delete", "options", "head")


@dataclass(frozen=True)
class ClientGeneration:
    source: str
    operations: tuple[str, ...]
    skipped: tuple[str, ...]


def _quote(value: object) -> str:
    return json.dumps(str(value), ensure_ascii=True)


def _identifier(raw: str) -> str:
    name = re.sub(r"[^a-zA-Z0-9_$]", "_", raw)
    if not name or name[0].isdigit():
        name = "_" + name
    return name


def _ref_type(ref: str) -> str:
    prefix = "#/components/schemas/"
    if not ref.startswith(prefix):
        raise ValueError(f"Unsupported OpenAPI schema reference: {ref!r}")
    name = ref[len(prefix):].replace("~1", "/").replace("~0", "~")
    return "Schemas[" + _quote(name) + "]"


def _ts_type(spec: Any) -> str:
    """Translate common JSON Schema/OpenAPI 3.1 constructs conservatively."""
    if spec is True:
        return "unknown"
    if spec is False:
        return "never"
    if not isinstance(spec, dict):
        return "unknown"

    if "$ref" in spec:
        typ = _ref_type(spec["$ref"])
    elif "const" in spec:
        typ = json.dumps(spec["const"], ensure_ascii=True)
    elif isinstance(spec.get("enum"), list) and spec["enum"]:
        typ = " | ".join(json.dumps(v, ensure_ascii=True) for v in spec["enum"])
    elif "allOf" in spec:
        typ = " & ".join(f"({_ts_type(item)})" for item in spec["allOf"]) or "unknown"
    elif "anyOf" in spec or "oneOf" in spec:
        members = spec.get("anyOf", spec.get("oneOf", ()))
        typ = " | ".join(f"({_ts_type(item)})" for item in members) or "unknown"
    elif isinstance(spec.get("type"), list):
        typ = " | ".join(_ts_type({**spec, "type": item}) for item in spec["type"])
    elif spec.get("type") == "array":
        typ = f"Array<{_ts_type(spec.get('items', {}))}>"
    elif spec.get("type") == "object" or "properties" in spec:
        properties = spec.get("properties", {})
        required = set(spec.get("required", []))
        if not isinstance(properties, dict):
            properties = {}
        if properties:
            fields = [
                f"{_quote(name)}{'?' if name not in required else ''}: {_ts_type(value)};"
                for name, value in properties.items()
            ]
            typ = "{ " + " ".join(fields) + " }"
        else:
            extra = spec.get("additionalProperties", True)
            typ = (
                "Record<string, " + _ts_type(extra) + ">"
                if extra is not False else "Record<string, never>"
            )
    else:
        typ = {
            "string": "string",
            "number": "number",
            "integer": "number",
            "boolean": "boolean",
            "null": "null",
        }.get(spec.get("type"), "unknown")
    if spec.get("nullable") and typ != "null":
        typ = f"({typ} | null)"
    return typ


def _component_types(document: dict[str, Any]) -> str:
    components = document.get("components", {}).get("schemas", {})
    if not isinstance(components, dict):
        raise ValueError("OpenAPI components.schemas must be an object")
    lines = ["export interface Schemas {"]
    for name, definition in sorted(components.items()):
        lines.append(f"  {_quote(name)}: {_ts_type(definition)};")
    lines.append("}")
    return "\n".join(lines)


def _dereference(document: dict[str, Any], value: dict[str, Any]) -> dict[str, Any]:
    ref = value.get("$ref")
    if not ref:
        return value
    if not isinstance(ref, str) or not ref.startswith("#/components/parameters/"):
        raise ValueError(f"Unsupported parameter reference: {ref!r}")
    key = ref.split("/")[-1].replace("~1", "/").replace("~0", "~")
    param = document.get("components", {}).get("parameters", {}).get(key)
    if not isinstance(param, dict):
        raise ValueError(f"Missing OpenAPI parameter reference: {ref!r}")
    return param


def _params_type(params: list[dict[str, Any]]) -> tuple[str, bool]:
    if not params:
        return "{ }", False
    names: set[str] = set()
    fields: list[str] = []
    required = False
    for item in params:
        name = str(item["name"])
        if name in names:
            raise ValueError(f"Duplicate parameter: {name}")
        names.add(name)
        is_required = bool(item.get("required"))
        required = required or is_required
        fields.append(
            f"{_quote(name)}{'' if is_required else '?'}: {_ts_type(item.get('schema', {}))};"
        )
    return "{ " + " ".join(fields) + " }", required


def _json_body(operation: dict[str, Any]) -> tuple[str | None, bool, str | None]:
    req = operation.get("requestBody")
    if not req:
        return None, False, None
    if "$ref" in req:
        return None, False, "requestBody reference is not supported"
    content = req.get("content", {})
    media = content.get("application/json")
    if media is None:
        media = next((v for k, v in content.items() if k.endswith("+json")), None)
    if media is None:
        return None, False, "non-JSON request body is not supported"
    return _ts_type(media.get("schema", {})), bool(req.get("required")), None


def _success_type(operation: dict[str, Any]) -> tuple[str, str | None]:
    responses = operation.get("responses", {})
    possibilities: list[str] = []
    for code, value in sorted(responses.items()):
        if not (str(code).startswith("2") or str(code).upper() == "2XX"):
            continue
        if not isinstance(value, dict) or "$ref" in value:
            return "unknown", "response reference is not supported"
        content = value.get("content", {})
        if not content:
            possibilities.append("void")
            continue
        json_media = content.get("application/json")
        if json_media is None:
            json_media = next(
                (v for k, v in content.items() if k.endswith("+json")), None
            )
        if json_media is None:
            return "unknown", "non-JSON success response is not supported"
        possibilities.append(_ts_type(json_media.get("schema", {})))
    return " | ".join(dict.fromkeys(possibilities)) or "unknown", None


def _runtime_source() -> str:
    return """type ApiOptions = {
  path?: Record<string, string | number | boolean>;
  query?: Record<string, unknown>;
  header?: Record<string, string | number | boolean>;
  body?: unknown;
  headers?: HeadersInit;
  signal?: AbortSignal;
  credentials?: RequestCredentials;
};

export class QPyServeApiError extends Error {
  constructor(
    readonly operation: string,
    readonly status: number,
    readonly traceId: string | null,
  ) {
    super(operation + " failed: HTTP " + status);
    this.name = "QPyServeApiError";
  }
}

async function request<T>(
  operation: string, method: string, template: string,
  options: ApiOptions = {}, bodyRequired = false,
): Promise<T> {
  const path = template.replace(/\\{([^}]+)\\}/g, (_match, key: string) => {
    const value = options.path?.[key];
    if (value === undefined || value === null) {
      throw new Error("Missing path parameter " + key + " for " + operation);
    }
    return encodeURIComponent(String(value));
  });
  const query = new URLSearchParams();
  for (const [key, value] of Object.entries(options.query ?? {})) {
    if (value === null || value === undefined) continue;
    for (const item of Array.isArray(value) ? value : [value]) {
      if (item !== null && item !== undefined) query.append(key, String(item));
    }
  }
  const url = query.size ? path + "?" + query.toString() : path;
  const headers = new Headers(options.headers);
  for (const [name, value] of Object.entries(options.header ?? {})) {
    headers.set(name, String(value));
  }
  const withBody = options.body !== undefined;
  if (bodyRequired && !withBody) {
    throw new Error("Missing JSON body for " + operation);
  }
  if (withBody && !headers.has("Content-Type")) {
    headers.set("Content-Type", "application/json");
  }
  // QPyServe Trace patches fetch in dev to attach a correlation ID.
  // The generated client sends no telemetry or extra request bodies.
  const response = await fetch(url, {
    method, headers, signal: options.signal, credentials: options.credentials,
    body: withBody ? JSON.stringify(options.body) : undefined,
  });
  if (!response.ok) {
    throw new QPyServeApiError(
      operation, response.status, response.headers.get("x-qpyserve-trace-id"),
    );
  }
  if (response.status === 204 || response.status === 205 || method === "HEAD") {
    return undefined as T;
  }
  const contentType = response.headers.get("content-type") || "";
  if (!contentType.includes("json")) return undefined as T;
  return await response.json() as T;
}
"""


def generate_client(document: dict[str, Any]) -> ClientGeneration:
    """Deterministically generate TypeScript; report unsupported HTTP operations."""
    names: set[str] = set()
    functions: list[str] = []
    generated: list[str] = []
    skipped: list[str] = []
    paths = document.get("paths", {})
    if not isinstance(paths, dict):
        raise ValueError("OpenAPI paths must be an object")
    for path, entry in sorted(paths.items()):
        if not isinstance(entry, dict) or not path.startswith("/"):
            continue
        for method in _METHODS:
            operation = entry.get(method)
            if not isinstance(operation, dict):
                continue
            operation_id = str(operation.get("operationId") or f"{method}_{path}")
            name = _identifier(operation_id)
            if name in names:
                skipped.append(f"{method.upper()} {path}: duplicate operation ID {name}")
                continue
            try:
                combined = [
                    _dereference(document, p)
                    for p in [*entry.get("parameters", []), *operation.get("parameters", [])]
                ]
                by_key = {(p["in"], p["name"]): p for p in combined}
                params = list(by_key.values())
                unsupported = [
                    p["in"] for p in params if p["in"] not in ("path", "query", "header")
                ]
                if unsupported:
                    skipped.append(
                        f"{method.upper()} {path}: unsupported parameter location {unsupported[0]}"
                    )
                    continue
                by_location = {
                    place: _params_type([p for p in params if p["in"] == place])
                    for place in ("path", "query", "header")
                }
                body_type, body_required, body_reason = _json_body(operation)
                return_type, response_reason = _success_type(operation)
                if body_reason or response_reason:
                    skipped.append(f"{method.upper()} {path}: {body_reason or response_reason}")
                    continue
            except (KeyError, TypeError, ValueError) as exc:
                skipped.append(f"{method.upper()} {path}: {exc}")
                continue
            names.add(name)
            generated.append(name)
            fields: list[str] = []
            for place in ("path", "query", "header"):
                spec, required = by_location[place]
                if spec != "{ }":
                    fields.append(f"{place}{'' if required else '?'}: {spec};")
            if body_type is not None:
                fields.append(f"body{'' if body_required else '?'}: {body_type};")
            fields.extend((
                "headers?: HeadersInit;",
                "signal?: AbortSignal;",
                "credentials?: RequestCredentials;",
            ))
            options_type = "{ " + " ".join(fields) + " }"
            has_required = any(by_location[k][1] for k in by_location) or body_required
            arg = (f"options: {options_type}" if has_required
                   else f"options: {options_type} = {{}}")
            functions.append(
                f"  {_quote(name)}: ({arg}): Promise<{return_type}> =>\n"
                f"    request<{return_type}>({_quote(name)}, {_quote(method.upper())}, "
                f"{_quote(path)}, options, {'true' if body_required else 'false'}),"
            )

    source = (
        _MARKER + "\n"
        "// Source: your FastAPI OpenAPI schema. Regenerate with qpyserve api.\n"
        "// No external requests or runtime dependencies beyond browser fetch.\n\n"
        + _component_types(document)
        + "\n\n"
        + _runtime_source()
        + "\nexport const api = {\n"
        + ("\n".join(functions) + "\n" if functions else "")
        + "};\n"
    )
    return ClientGeneration(source, tuple(generated), tuple(skipped))


def client_output(project: Path, destination: str | Path | None = None) -> Path:
    """Constrain generated TypeScript to the project's frontend tree."""
    project = project.resolve()
    frontend = (project / "frontend").resolve()
    if not frontend.is_dir() or not frontend.is_relative_to(project):
        raise ValueError("Missing project frontend/ directory")
    if destination is None:
        target = frontend / ("src/qpyserve-api.ts" if (frontend / "src").is_dir()
                             else "qpyserve-api.ts")
    else:
        target = Path(destination)
        if not target.is_absolute():
            target = project / target
    if target.suffix != ".ts" or target.is_symlink():
        raise ValueError("Generated client must be a non-symlink .ts file")
    if not target.parent.resolve().is_relative_to(frontend):
        raise ValueError("Generated client must remain inside frontend/")
    if any(part in {"node_modules", "dist", ".git"} or part.startswith(".")
           for part in target.relative_to(project).parts):
        raise ValueError("Cannot generate into hidden or build directories")
    return target


def save_client(
    generation: ClientGeneration, destination: Path, *, check: bool = False,
) -> dict[str, Any]:
    """Only overwrite generated files and avoid rewriting unchanged content."""
    if destination.is_symlink():
        raise ValueError("Refusing to overwrite a symlink")
    existing = destination.read_text(encoding="utf-8") if destination.is_file() else None
    if existing is not None and not existing.startswith(_MARKER):
        raise FileExistsError(f"Refusing to overwrite non-generated file: {destination}")
    drift = existing != generation.source
    if drift and not check:
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            "w", encoding="utf-8", newline="\n", dir=destination.parent,
            prefix=".qpyserve-", suffix=".tmp", delete=False,
        ) as temp:
            temp.write(generation.source)
            temp_name = temp.name
        try:
            os.replace(temp_name, destination)
        finally:
            Path(temp_name).unlink(missing_ok=True)
    return {
        "output": str(destination),
        "written": bool(drift and not check),
        "drift": drift,
        "check": check,
        "operations": list(generation.operations),
        "skipped": list(generation.skipped),
    }


def load_app(project: Path, app_import: str = "main:app") -> FastAPI:
    """Import a trusted project for explicit CLI generation.

    Unlike qpyserve doctor, this executes application imports.
    """
    module_name, colon, attr = app_import.partition(":")
    if not colon or not module_name or not attr or not all(
        re.fullmatch(r"[A-Za-z_]\w*", part)
        for part in (*module_name.split("."), *attr.split("."))
    ):
        raise ValueError("Expected --app module:variable, such as main:app")
    sys.path.insert(0, str(project.resolve()))
    previous = sys.modules.pop(module_name, None)
    try:
        module = importlib.import_module(module_name)
        obj: Any = module
        for key in attr.split("."):
            obj = getattr(obj, key)
        if not isinstance(obj, FastAPI):
            raise TypeError(f"{app_import} does not resolve to FastAPI")
        return obj
    finally:
        sys.path.pop(0)
        if previous is not None:
            sys.modules[module_name] = previous
        else:
            sys.modules.pop(module_name, None)
