"""Generate reviewable, non-destructive deployment files for QPyServe projects.

This command prepares deployment assets. It never deploys or accesses credentials.
"""

from __future__ import annotations

import json
from pathlib import Path
import re
from typing import Any

from ._tooling import has_vite, package_manager


_IMPORT = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*:[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*$")
_SERVICE = re.compile(r"^[a-z][a-z0-9-]{0,62}$")


def _dockerignore() -> str:
    return """# Keep credentials, local environments, and build debris out of Docker context.
.git
.github
.venv
venv
**/__pycache__
**/*.pyc
**/.pytest_cache
**/node_modules
frontend/dist
build
dist
*.egg-info
.env
.env.*
**/.env
**/.env.*
.npmrc
**/.npmrc
.pypirc
**/.pypirc
.netrc
**/.netrc
.aws
**/.aws
**/.ssh
**/*.pem
**/*.key
**/*.p12
**/*.pfx
**/*.sqlite
**/*.sqlite3
**/*.db
.qpyserve.*
**/.qpyserve.*
"""


def _frontend_steps(frontend: Path) -> str:
    if not has_vite(frontend):
        return ""
    manager = package_manager(frontend)
    manifest = json.loads((frontend / "package.json").read_text(encoding="utf-8"))
    custom_build = "build" in manifest.get("scripts", {})
    if manager == "npm":
        install = "npm ci" if (
            (frontend / "package-lock.json").is_file()
            or (frontend / "npm-shrinkwrap.json").is_file()
        ) else "npm install --no-audit --no-fund"
        build = "npm run build" if custom_build else "npm exec --no -- vite build"
        base = "node:22-bookworm-slim"
    elif manager == "pnpm":
        install = "corepack enable && pnpm install"
        if (frontend / "pnpm-lock.yaml").is_file():
            install += " --frozen-lockfile"
        build = "pnpm run build" if custom_build else "pnpm exec vite build"
        base = "node:22-bookworm-slim"
    elif manager == "yarn":
        # Yarn 1 and Berry accept 'yarn install'; immutable flags differ.
        install = "corepack enable && yarn install"
        build = "yarn build" if custom_build else "yarn vite build"
        base = "node:22-bookworm-slim"
    else:
        install = "bun install"
        if (frontend / "bun.lock").is_file() or (frontend / "bun.lockb").is_file():
            install += " --frozen-lockfile"
        build = "bun run build" if custom_build else "bunx --no-install vite build"
        base = "oven/bun:1"

    return (
        f"FROM {base} AS frontend-build\n"
        "WORKDIR /app/frontend\n"
        "COPY frontend/ ./\n"
        f"RUN {install}\n"
        f"RUN {build}\n\n"
    )


def _dockerfile(frontend: Path) -> str:
    vite = has_vite(frontend)
    result = (
        "# Generated by qpyserve ship. Review before deploying.\n"
        + _frontend_steps(frontend)
        + "FROM python:3.12-slim\n"
        "WORKDIR /app\n"
        "ENV PYTHONUNBUFFERED=1\n"
        "COPY . .\n"
    )
    if vite:
        result += "COPY --from=frontend-build /app/frontend/dist ./frontend/dist\n"
    result += (
        'RUN python -m pip install --no-cache-dir "qpyserve>=0.4,<1" \\\n'
        ' && if [ -f requirements.txt ]; then python -m pip install --no-cache-dir -r requirements.txt; fi \\\n'
        ' && if [ -f pyproject.toml ]; then python -m pip install --no-cache-dir .; fi\n'
        "EXPOSE 10000\n"
        'CMD ["python", "docker-start.py"]\n'
    )
    return result


def _startup(app_import: str) -> str:
    module, variable = app_import.split(":", 1)
    return (
        '"""Production entry point generated by qpyserve ship.\n'
        "Set PORT on your hosting provider if needed.\n"
        '"""\n\n'
        "from importlib import import_module\n"
        "import os\n\n"
        "from qpyserve import run\n\n"
        f"app = import_module({module!r})\n"
        f"for attribute in {variable!r}.split('.'):\n"
        "    app = getattr(app, attribute)\n\n"
        'if __name__ == "__main__":\n'
        "    run(\n"
        '        app, frontend="frontend", port=int(os.environ.get("PORT", "10000")),\n'
        f'        host="0.0.0.0", mode="production", app_import={app_import!r}, trace=False,\n'
        "    )\n"
    )


def prepare_ship(
    directory: str | Path = ".",
    *,
    app_import: str = "main:app",
    service_name: str | None = None,
) -> dict[str, Any]:
    """Prepare Docker + Render Blueprint; never overwrite or deploy."""
    project = Path(directory).expanduser().resolve()
    if not project.is_dir():
        raise FileNotFoundError(f"Project directory not found: {project}")
    if not _IMPORT.fullmatch(app_import):
        raise ValueError("App import must be module:variable, such as main:app")
    module = app_import.split(":", 1)[0].replace(".", "/")
    if not (
        (project / f"{module}.py").is_file()
        or (project / module / "__init__.py").is_file()
    ):
        raise FileNotFoundError(f"Cannot find Python module for {app_import!r}")
    frontend = project / "frontend"
    if not frontend.is_dir() or not (frontend / "index.html").is_file():
        raise FileNotFoundError("Expected frontend/index.html in the project")
    if frontend.is_symlink() or not frontend.resolve().is_relative_to(project):
        raise ValueError("Frontend must be inside the project")

    if service_name is None:
        slug = re.sub(r"[^a-z0-9]+", "-", project.name.lower()).strip("-")
        service_name = slug if slug and slug[0].isalpha() else "qpyserve-app"
        service_name = service_name[:63].rstrip("-")
    if not _SERVICE.fullmatch(service_name):
        raise ValueError("Render service name must use lowercase letters, digits and hyphens")

    output = {
        "Dockerfile": _dockerfile(frontend),
        ".dockerignore": _dockerignore(),
        "docker-start.py": _startup(app_import),
        "render.yaml": (
            "services:\n"
            "  - type: web\n"
            f"    name: {service_name}\n"
            "    runtime: docker\n"
            "    plan: free\n"
            "    dockerfilePath: ./Dockerfile\n"
            "    healthCheckPath: /__qpyserve/health\n"
        ),
    }
    existing = [path for path in output if (project / path).exists() or (project / path).is_symlink()]
    if existing:
        raise FileExistsError(
            "Would overwrite existing deployment files: " + ", ".join(existing)
            + ". Review or move them first."
        )
    written: list[Path] = []
    try:
        for name, content in output.items():
            path = project / name
            with path.open("x", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            written.append(path)
    except OSError:
        for path in written:
            path.unlink(missing_ok=True)
        raise
    return {
        "project": str(project),
        "files": list(output),
        "frontend": "vite" if has_vite(frontend) else "html",
        "service": service_name,
        "deployed": False,
        "next_step": "Review generated files, push to GitHub, create a Render Blueprint.",
        "warnings": [
            "Render free instances sleep on idle and have ephemeral filesystems.",
            "Deployment is public; configure authentication and secrets in your app/provider.",
            "Verify Docker build and startup with your actual project dependencies.",
        ],
    }
